def _fake_service_account_json():
    """Minimal service-account JSON shape — google-auth validates the
    `type` field strictly but accepts dummy values for the rest if the
    transport is mocked. We stub the credentials object instead."""
    return json.dumps({
        "type": "service_account",
        "project_id": "bug-hunter-test",
        "private_key_id": "0" * 40,
        "private_key": "-----BEGIN PRIVATE KEY-----\nfake\n-----END PRIVATE KEY-----\n",
        "client_email": "test@bug-hunter-test.iam.gserviceaccount.com",
        "client_id": "100000000000000000000",
    })


def _setup_push(monkeypatch, sa_json=None, project_id="bug-hunter-test"):
    """Wire up an enabled push service with a stub credentials object.

    Returns the cache singleton for inspection. Caller can patch
    `_credential_cache.access_token` to control what token is returned.
    """
    from app import push_service
    monkeypatch.setenv("FIREBASE_PROJECT_ID", project_id)
    monkeypatch.setenv("FIREBASE_SA_JSON", sa_json or _fake_service_account_json())
    from app.config import get_settings
    get_settings.cache_clear()
    push_service.reset_credentials_cache()
    # Force the cache to materialise so we can stub access_token below.
    cache = push_service._get_cache()
    if not cache.enabled:
        # google-auth refused to parse our fake JSON. Stub the cache to
        # look enabled and return a hard-coded token.
        cache._enabled = True
        cache._credentials = MagicMock()
    monkeypatch.setattr(cache, "access_token", lambda: "fake-access-token")
    return cache


def test_push_sends_when_token_present(admin_client, monkeypatch):
    from app import push_service
    from app.database import SessionLocal
    from app.models import DeviceToken

    me = admin_client.admin_me
    user_id = me["id"]

    # Register a token first.
    admin_client.post("/api/devices/register", json={"token": _FAKE_TOK_FIRE[0]})

    _setup_push(monkeypatch)

    sent_payloads: list[dict] = []

    def transport_handler(request: httpx.Request) -> httpx.Response:
        sent_payloads.append(json.loads(request.content.decode("utf-8")))
        return httpx.Response(200, json={"name": "projects/bug-hunter-test/messages/1"})

    transport = httpx.MockTransport(transport_handler)
    real_client_cls = httpx.Client

    def patched_client(*args, **kwargs):
        kwargs["transport"] = transport
        return real_client_cls(*args, **kwargs)

    monkeypatch.setattr(push_service.httpx, "Client", patched_client)

    with SessionLocal() as db:
        sent = push_service.send_to_user(
            db, user_id,
            title="Hello", body="World",
            channel=push_service.CHANNEL_ASSIGNMENTS,
            deep_link="app://bughunter/bug/42",
            tag="bug:42",
        )
    assert sent == 1, "expected one successful POST"
    assert len(sent_payloads) == 1
    payload = sent_payloads[0]["message"]
    assert payload["token"] == _FAKE_TOK_FIRE[0]
    assert payload["data"]["title"] == "Hello"
    assert payload["data"]["body"] == "World"
    assert payload["data"]["channel"] == "assignments"
    assert payload["data"]["deep_link"] == "app://bughunter/bug/42"
    assert payload["data"]["tag"] == "bug:42"
    # We never use notification payloads — verify they are absent.
    assert "notification" not in payload


