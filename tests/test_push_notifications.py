def test_mention_regex_detects_inline_at():
    from app.push_notify import _MENTION_RE
    assert _MENTION_RE.search("Hey @alice please look at this")
    assert _MENTION_RE.search("ping @bob.smith")
    assert not _MENTION_RE.search("plain text with no at-sign")
    # The regex is intentionally pessimistic: any '@' followed by
    # alphanumerics matches, even `alice@example.com`. The targeting
    # itself is separate; this regex only powers the
    # "should this push be on the high-priority mentions channel"
    # heuristic. False positives mean we use the high-priority channel
    # for a non-mention — annoying but not a leak.
    assert _MENTION_RE.search("email-like alice@example.com matches too")
