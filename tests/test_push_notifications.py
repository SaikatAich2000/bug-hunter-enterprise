def test_device_token_isolation_across_orgs(two_orgs):
    """Org A registers a token. Org B's admin must not be able to
    delete it (they don't own it). Bob's DELETE silently 204s — the
    semantic is 'I don't have this token registered to me' — and Org A's
    token row is left intact."""
    from app.database import SessionLocal
    from app.models import DeviceToken
    c_a, c_b, _me_a, _me_b = two_orgs
    tok = _FAKE_TOK_CROSS_ORG[0]
    r = c_a.post("/api/devices/register", json={"token": tok})
    assert r.status_code == 200, r.text

    # Bob (Org B) DELETEs the same token — should succeed with 204 but
    # not actually remove Alice's row.
    r = c_b.delete(f"/api/devices/{tok}")
    assert r.status_code == 204

    with SessionLocal() as db:
        row = db.query(DeviceToken).filter(DeviceToken.token == tok).first()
        assert row is not None, "Bob managed to delete Alice's token — isolation bug"


