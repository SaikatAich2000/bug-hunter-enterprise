"""Tests for the v2.10 push-notifications subsystem.

Coverage matrix:
  - DeviceToken register / unregister round-trip + idempotency
  - Cross-org isolation: org A's user cannot operate on org B's tokens
  - NotificationPreferences GET returns derived defaults (all-on) when
    no row exists; PUT upserts and PATCH-style merges
  - push_service.send_to_user respects channel preferences (mentions
    off → mention pushes drop, others fire)
  - push_service stale-token cleanup deletes UNREGISTERED rows
  - push_service short-circuits when FIREBASE_PROJECT_ID is blank
  - push_notify @-mention heuristic upgrades the channel

We mock httpx + google-auth so the suite never reaches Firebase. The
goal is to verify our payload shape, prefs gating, and cleanup rules,
not to test Firebase's API.
"""
from __future__ import annotations

import json
from unittest.mock import MagicMock, patch

import httpx
import pytest


